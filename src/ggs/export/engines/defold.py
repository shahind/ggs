"""Defold exporter: ``.atlas`` + ``.collection`` + Lua data module + player script, all plain text.

Defold is +y up and rotates counter-clockwise, so package y and angles are negated. Resource paths in Defold
files are absolute from the project root: ``project_path`` (default ``/ggs/<name>``) is where the folder must sit.

Collection layout:
    root            script component (plays clips)
      pelvis        bone game objects, nested like the bones; position (0, -attach * parent length)
        pelvis_art  sprite, offset so the part's pivot sits on the bone origin; z = draw order * 0.001
        torso ...
"""

from __future__ import annotations

import math
from pathlib import Path

from ggs.export.engines.common import (
    Package,
    base_draw_index,
    draw_index_tracks,
    ident,
    load_package,
    local_unwrapped,
)

DEFOLD_MIN = "1.9.0"
Z_STEP = 0.001


def _q(s: str) -> str:
    """Protobuf text-format string literal."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _num(x: float) -> str:
    s = f"{x:.6f}".rstrip("0").rstrip(".")
    return "0.0" if s in ("", "-0") else (s if "." in s else s + ".0")


def _xform(pos=(0.0, 0.0, 0.0), deg: float = 0.0, scale: float = 1.0, indent: str = "") -> list[str]:
    h = math.radians(deg) / 2
    return [
        f"{indent}position {{", f"{indent}  x: {_num(pos[0])}", f"{indent}  y: {_num(pos[1])}",
        f"{indent}  z: {_num(pos[2])}", f"{indent}}}",
        f"{indent}rotation {{", f"{indent}  x: 0.0", f"{indent}  y: 0.0", f"{indent}  z: {_num(math.sin(h))}",
        f"{indent}  w: {_num(math.cos(h))}", f"{indent}}}",
        f"{indent}scale3 {{", f"{indent}  x: {_num(scale)}", f"{indent}  y: {_num(scale)}", f"{indent}  z: 1.0",
        f"{indent}}}",
    ]


def _sprite_go(atlas_path: str, animation: str) -> str:
    sprite = "\n".join([
        f"default_animation: {_q(animation)}",
        'material: "/builtins/materials/sprite.material"',
        "blend_mode: BLEND_MODE_ALPHA",
        "textures {",
        '  sampler: "texture_sampler"',
        f"  texture: {_q(atlas_path)}",
        "}",
        "",
    ])
    return "\n".join([
        "embedded_components {",
        '  id: "sprite"',
        '  type: "sprite"',
        f"  data: {_q(sprite)}",
        *_xform(indent="  "),
        "}",
        "",
    ])


def _script_go(script_path: str) -> str:
    return "\n".join(["components {", '  id: "rig"', f"  component: {_q(script_path)}", *_xform(indent="  "),
                      "}", ""])


def _instance(iid: str, children: list[str], data: str, pos, deg: float, scale: float = 1.0) -> list[str]:
    return ["embedded_instances {", f"  id: {_q(iid)}", *[f"  children: {_q(c)}" for c in children],
            f"  data: {_q(data)}", *_xform(pos, deg, scale, "  "), "}"]


def _art_offset(rect: dict, pivot: dict, art_angle: float) -> tuple[float, float]:
    """Sprite centre relative to the pivot, in Defold (y-up) bone space after rotating by art_angle."""
    vx, vy = rect["w"] / 2 - pivot["x"], -(rect["h"] / 2 - pivot["y"])
    a = math.radians(art_angle)
    return vx * math.cos(a) - vy * math.sin(a), vx * math.sin(a) + vy * math.cos(a)


def _lua(v, indent: str = "") -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v) if isinstance(v, int) else _num(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "{" + ", ".join(_lua(x) for x in v) + "}"
    if isinstance(v, dict):
        inner = indent + "  "
        items = [f"{inner}{k} = {_lua(x, inner)}" if k.isidentifier() else f'{inner}["{k}"] = {_lua(x, inner)}'
                 for k, x in v.items()]
        return "{\n" + ",\n".join(items) + "\n" + indent + "}"
    raise TypeError(type(v))


SCRIPT = """-- GGS rig player for Defold. Generated by ggs; safe to edit.
-- Messages: play {clip = "walk"}, stop {}, set_head {variant = "blink"} (variant = nil for the normal head).
local data = require "{module}"

go.property("speed", 1)
go.property("autoplay", true)

local Z_STEP = {z_step}

local function lerp(a, b, t) return a + (b - a) * t end

function init(self)
	self.bone, self.art, self.variants = {}, {}, {}
	for _, name in ipairs(data.bones) do
		self.bone[name] = go.get_id(name)
		self.art[name] = go.get_id(name .. "_art")
	end
	for bone, tint in pairs(data.tints) do
		go.set(msg.url(nil, self.art[bone], "sprite"), "tint", vmath.vector4(tint, tint, tint, 1))
	end
	for _, v in ipairs(data.head_variants) do
		self.variants[v] = msg.url(nil, go.get_id(data.head_bone .. "_art_" .. v), "sprite")
		msg.post(self.variants[v], "disable")
	end
	self.time = 0
	if self.autoplay and data.clip_names[1] then self.clip = data.clips[data.clip_names[1]] end
end

function update(self, dt)
	local c = self.clip
	if not c then return end
	self.time = self.time + dt * self.speed
	local n = c.frame_count
	local f = self.time * c.fps
	if c.loop then f = f % n else f = math.min(f, n - 1) end
	local i0 = math.floor(f)
	local a = f - i0
	local i1 = i0 + 1
	if i1 >= n then i1 = c.loop and 0 or n - 1 end
	i0, i1 = i0 + 1, i1 + 1
	go.set_position(vmath.vector3(lerp(c.root_x[i0], c.root_x[i1], a), -lerp(c.root_y[i0], c.root_y[i1], a), 0),
		self.bone[data.root])
	for bone, v in pairs(c.angles) do
		local d = (v[i1] - v[i0] + 180) % 360 - 180
		go.set_rotation(vmath.quat_rotation_z(-math.rad(v[i0] + d * a)), self.bone[bone])
	end
	for bone, v in pairs(c.draw_index) do
		go.set(self.art[bone], "position.z", v[i0] * Z_STEP)
	end
end

function on_message(self, message_id, message, sender)
	if message_id == hash("play") then
		self.clip = data.clips[message.clip]
		self.time = 0
	elseif message_id == hash("stop") then
		self.clip = nil
	elseif message_id == hash("set_head") then
		for name, url in pairs(self.variants) do msg.post(url, name == message.variant and "enable" or "disable") end
		msg.post(msg.url(nil, self.art[data.head_bone], "sprite"),
			(message.variant and self.variants[message.variant]) and "disable" or "enable")
	end
end
"""


def write_defold(package_dir: str | Path, project_path: str | None = None) -> Path:
    """Add Defold files to the rig package folder. ``project_path`` = where the folder will sit in the Defold
    project (absolute, e.g. ``/characters/hero``)."""
    from PIL import Image

    package_dir = Path(package_dir)
    pkg: Package = load_package(package_dir)
    name = ident(pkg.name)
    base = (project_path or f"/ggs/{name}").rstrip("/")
    if not base.startswith("/"):
        raise ValueError("project path must be absolute inside the Defold project, e.g. /ggs/hero")
    module = base.strip("/").replace("/", ".") + f".{name}_rig"
    atlas_path = f"{base}/{name}.atlas"
    script_path = f"{base}/{name}_rig.script"

    # individual part images (Defold atlases list image files)
    atlas_img = Image.open(package_dir / pkg.doc["image"]).convert("RGBA")
    (package_dir / "parts").mkdir(exist_ok=True)
    images = []
    held = pkg.doc.get("items", [])
    for item in [*pkg.doc["parts"], *pkg.doc.get("head_variants", []), *held]:
        r = item["rect"]
        crop = atlas_img.crop((r["x"], r["y"], r["x"] + r["w"], r["y"] + r["h"]))
        fname = (item["name"] if item in pkg.doc["parts"] else
                 f"item_{item['name']}" if item in held else f"head_{item['name']}")
        crop.save(package_dir / "parts" / f"{fname}.png")
        images.append(fname)
    atlas = [f'images {{\n  image: "{base}/parts/{f}.png"\n}}' for f in images]
    atlas += ["margin: 2", "extrude_borders: 1", "inner_padding: 0", ""]
    (package_dir / f"{name}.atlas").write_text("\n".join(atlas), encoding="utf-8", newline="\n")

    first = next(iter(pkg.clips.values()), None)
    local0 = local_unwrapped(pkg, first) if first else {}
    rest = pkg.doc["rest_pose"]
    z0 = base_draw_index(pkg)
    head_bone, variants = None, [v["name"] for v in pkg.doc.get("head_variants", [])]
    lines = [f"name: {_q(name)}", "scale_along_z: 0"]
    lines += _instance("root", [pkg.root], _script_go(script_path), (0, 0, 0), 0.0)
    for b in pkg.ordered_bones():
        bone = pkg.bone(b)
        part, far = pkg.part_for(b)
        if bone["parent"] is None:
            x = first["root"]["x"][0] if first else rest["root"]["x"]
            y = first["root"]["y"][0] if first else rest["root"]["y"]
            pos = (x, -y, 0.0)
            ang = local0[b][0] if first else rest["angles"][b]
        else:
            pos = (0.0, -bone["attach"] * pkg.bone(bone["parent"])["length"], 0.0)
            ang = local0[b][0] if first else rest["angles"][b] - rest["angles"][bone["parent"]]
        kids = [*pkg.children(b), f"{b}_art", *[f"{b}_item_{i['name']}" for i in held if i["bone"] == b]]
        if part["name"] == "head" and not far:
            head_bone = b
            kids += [f"{b}_art_{v}" for v in variants]
        lines += _instance(b, kids, "", pos, -ang)
        s = bone["length"] / part["length_px"] if part["length_px"] > 0 else 1.0
        ox, oy = _art_offset(part["rect"], part["pivot"], part["art_angle"])
        lines += _instance(f"{b}_art", [], _sprite_go(atlas_path, part["name"]),
                           (ox * s, oy * s, z0[b] * Z_STEP), part["art_angle"], s)
        if b == head_bone:
            for v in pkg.doc.get("head_variants", []):
                vx, vy = _art_offset(v["rect"], v["pivot"], part["art_angle"])
                lines += _instance(f"{b}_art_{v['name']}", [], _sprite_go(atlas_path, f"head_{v['name']}"),
                                   (vx * s, vy * s, z0[b] * Z_STEP), part["art_angle"], s)
        for it in held:
            if it["bone"] != b:
                continue
            length = bone["length"]  # held item: fixed on the hand at its socket, above every part
            deg = it["art_angle"] - it["hold_angle"]
            ix, iy = _art_offset(it["rect"], it["pivot"], deg)
            lines += _instance(f"{b}_item_{it['name']}", [], _sprite_go(atlas_path, f"item_{it['name']}"),
                               (-it["socket_offset"] * length + ix, -it["socket_t"] * length + iy,
                                len(pkg.doc["draw_order"]) * Z_STEP), deg, 1.0)
    coll = package_dir / f"{name}.collection"
    coll.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    tints = {}
    for p in pkg.doc["parts"]:
        for bone_name in p["bones"][1:]:
            tints[bone_name] = p["far_tint"]
    clips = {}
    for cname, c in pkg.clips.items():
        clips[cname] = {
            "fps": c["fps"], "frame_count": c["frame_count"], "loop": c["loop"],
            "loop_travel_px": c["loop_travel_px"], "root_x": c["root"]["x"], "root_y": c["root"]["y"],
            "angles": local_unwrapped(pkg, c), "draw_index": draw_index_tracks(pkg, c),
        }
    data = {"root": pkg.root, "head_bone": head_bone or "", "bones": pkg.ordered_bones(), "tints": tints,
            "head_variants": variants if head_bone else [], "clip_names": list(pkg.clips), "clips": clips}
    (package_dir / f"{name}_rig.lua").write_text(
        "-- Generated by ggs from a rig package. Angles are package angles (degrees, clockwise, relative to\n"
        "-- the parent); the player script negates them for Defold.\nreturn " + _lua(data) + "\n",
        encoding="utf-8", newline="\n")
    (package_dir / f"{name}_rig.script").write_text(
        SCRIPT.replace("{module}", module).replace("{z_step}", _num(Z_STEP)), encoding="utf-8", newline="\n")
    (package_dir / "README_DEFOLD.txt").write_text(
        f"Defold {DEFOLD_MIN}+:\n"
        f"1. Copy this folder into your Defold project so that it sits at {base}/\n"
        f"   (re-export with --defold-path to choose another location).\n"
        f"2. Add {base}/{name}.collection to your main collection (Add Collection File).\n"
        f"3. Run: it autoplays '{next(iter(pkg.clips), '')}'. Send messages to the 'root' instance's 'rig'\n"
        "   component: play {clip = \"walk\"}, stop {}, set_head {variant = \"blink\"}.\n"
        "The 'root' game object's origin is the ground point under the character. Sprites use z between\n"
        "0 and 0.015 for draw order, inside the default render script's range.\n",
        encoding="utf-8", newline="\n")
    return coll
